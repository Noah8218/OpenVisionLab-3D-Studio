            "Depth" => "깊이",
            "Normal" => "노멀",
            "Confidence" => "신뢰도",
            "Signal/Noise" => "신호/잡음",
            "Thermal" => "열화상",
            "Deviation" => "편차",
            "Balanced" => "균형",
            "Detailed" => "상세",
            "Fast" => "빠름",
            "Loaded" => "로드됨",
            "Missing" => "누락됨",
            "Pending" => "대기",
            "Matched" => "일치",
            "Failed" => "실패",
            "ViewerFailed" => "뷰어 실패",
