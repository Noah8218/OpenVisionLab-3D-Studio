    public string Resolve(string key, string korean, string english)
    {
        var value = OpenVisionLanguageService.T(key);
        return string.Equals(value, key, StringComparison.Ordinal)
            ? OpenVisionLanguageService.CurrentLanguage == OpenVisionLanguage.English ? english : korean
            : value;
    }

    public string LocalizeRuntimeText(object? value, string? mode = null)
    {
        var text = value?.ToString() ?? string.Empty;
        if (string.Equals(mode, "PointSizeLabel", StringComparison.Ordinal)
            && value is IFormattable formattable)
        {
            text = formattable.ToString("F1", CultureInfo.CurrentCulture) ?? text;
        }

        if (string.Equals(mode, "LineFitPointState", StringComparison.Ordinal)
            && value is bool isInlier)
        {
            text = isInlier ? "Inlier" : "Outlier";
        }

        if (string.Equals(mode, "SurfaceMatchDecision", StringComparison.Ordinal))
        {
            return OpenVisionLanguageService.CurrentLanguage == OpenVisionLanguage.English
                ? text
                : text switch
                {
                    "PASS" => "통과",
                    "FAIL" => "실패",
                    "REJECTED" => "거부됨",
                    "NO DECISION" => "판정 없음",
                    _ => text
                };
        }

        if (OpenVisionLanguageService.CurrentLanguage == OpenVisionLanguage.English)
        {
            return Format(text, mode, "Selection", "Pick");
        }

        var localized = text switch
        {
            "Point" => "포인트",
            "Points" => "포인트",
            "Profile" => "프로파일",
            "Wireframe" => "와이어프레임",
